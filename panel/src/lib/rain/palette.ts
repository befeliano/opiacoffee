const exact = new Map<number, number>();
for (const [r, g, b, a, dbz] of UNIVERSAL_BLUE) exact.set(((r << 24) | (g << 16) | (b << 8) | a) >>> 0, dbz);
const nearestCache = new Map<number, number>();

/** Piksel rengini dBZ'ye çevirir; saydam piksel 0 (yağış yok). Tabloda olmayan renk en yakın renge eşlenir. */
export function dbzOf(r: number, g: number, b: number, a: number): number {
  if (a === 0) return 0;
  const key = ((r << 24) | (g << 16) | (b << 8) | a) >>> 0;
  const hit = exact.get(key) ?? nearestCache.get(key);
  if (hit !== undefined) return hit;
  let best = Infinity;
  let dbz = 0;
  for (const [pr, pg, pb, pa, d] of UNIVERSAL_BLUE) {
    const dist = (pr - r) ** 2 + (pg - g) ** 2 + (pb - b) ** 2 + (pa - a) ** 2;
    if (dist < best) {
      best = dist;
      dbz = d;
    }
  }
  nearestCache.set(key, dbz);
  return dbz;
}
